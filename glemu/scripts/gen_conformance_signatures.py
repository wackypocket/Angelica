#!/usr/bin/env python3
"""Lists each function's parameters as the OpenGL reference pages declare them, for GlGuidedProbe to call with valid arguments.

usage: gen_conformance_signatures.py <OpenGL-Refpages checkout>

Writes glemu/scripts/conformance-signatures.tsv, one line per parameter in order: function, parameter, C type, and the constants the
page names for it. A line holds facts about a function, not the page's text.
"""
import os
import re
import sys

PROTOTYPE = re.compile(r'<funcprototype>(.*?)</funcprototype>', re.S)
FUNCTION = re.compile(r'<function>(gl\w+)</function>')
PARAMDEF = re.compile(r'<paramdef>(.*?)</paramdef>', re.S)
PARAMETER = re.compile(r'<parameter>(\w+)</parameter>')
SECTION = re.compile(r'<refsect1[^>]*xml:id="parameters[^"]*"[^>]*>(.*?)</refsect1>', re.S)
ENTRY = re.compile(r'<varlistentry>\s*<term>(.*?)</term>\s*<listitem>(.*?)</listitem>', re.S)
CONSTANT = re.compile(r'<constant>(GL_\w+)</constant>')
OUT = 'glemu/scripts/conformance-signatures.tsv'


def constants(text):
    """What each parameter's own entry names. An entry for several parameters applies to each of them."""
    out = {}
    for section in SECTION.findall(text):
        for term, body in ENTRY.findall(section):
            found = list(dict.fromkeys(CONSTANT.findall(body)))
            for name in PARAMETER.findall(term):
                out.setdefault(name, found)
    return out


def main():
    if len(sys.argv) != 2 or sys.argv[1].startswith('-'):
        print(__doc__)
        return 2
    directory = os.path.join(sys.argv[1], 'gl4')
    lines = []
    seen = set()
    for page in sorted(os.listdir(directory)):
        if not page.startswith('gl') or not page.endswith('.xml'):
            continue
        text = open(os.path.join(directory, page), encoding='utf-8').read()
        allowed = constants(text)
        for prototype in PROTOTYPE.findall(text):
            function = FUNCTION.search(prototype).group(1)
            if function in seen:
                continue
            seen.add(function)
            for definition in PARAMDEF.findall(prototype):
                match = PARAMETER.search(definition)
                if match is None:
                    continue
                ctype = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', definition.replace(match.group(0), ''))).strip()
                lines.append('\t'.join((function, match.group(1), ctype, ','.join(allowed.get(match.group(1), [])))))
    with open(OUT, 'w') as f:
        f.write('# Generated by glemu/scripts/gen_conformance_signatures.py. Function, parameter, C type, constants the page names for it.\n')
        f.write('\n'.join(lines) + '\n')
    print(f'{len(seen)} functions, {len(lines)} parameters')


if __name__ == '__main__':
    sys.exit(main())
