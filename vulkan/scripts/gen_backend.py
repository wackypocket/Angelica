#!/usr/bin/env python3
"""Generates VulkanRenderBackend: every RenderBackend method VulkanGL implements, forwarded under the backend lock.

Run from the repository root after adding GL entry points to VulkanGL: python3 vulkan/scripts/gen_backend.py
"""
import re
import sys

RB = 'glsm/src/main/java/com/gtnewhorizons/angelica/glsm/backend/RenderBackend.java'
GL = 'vulkan/src/main/java/com/gtnewhorizons/angelica/vulkan/gl/VulkanGL.java'
BASE = 'vulkan/src/main/java/com/gtnewhorizons/angelica/vulkan/VulkanBackendBase.java'
OUT = 'vulkan/src/main/java/com/gtnewhorizons/angelica/vulkan/VulkanRenderBackend.java'

DECL = re.compile(r'^\s*(?:@\w+\s+)*(public|protected)\s+((?:abstract|final|static)\s+)*([\w<>\[\]\.]+)\s+(\w+)\(([^)]*)\)\s*(\{|;|throws)', re.M)


def norm_params(params):
    params = params.strip()
    if not params:
        return []
    out = []
    for p in params.split(','):
        p = p.strip().replace('final ', '')
        parts = p.rsplit(None, 1)
        out.append((parts[0].strip(), parts[1].strip()))
    return out


def methods(path):
    src = open(path).read()
    src = re.sub(r',\s*\n\s*', ', ', src)
    res = []
    for m in DECL.finditer(src):
        mods = m.group(2) or ''
        if 'static' in mods:
            continue
        res.append({'vis': m.group(1), 'final': 'final' in mods, 'abstract': 'abstract' in mods,
                    'ret': m.group(3), 'name': m.group(4), 'params': norm_params(m.group(5))})
    return res


def key(m):
    return m['name'] + '(' + ','.join(t for t, _ in m['params']) + ')'


rb = methods(RB)
gl = {key(m): m for m in methods(GL) if m['vis'] == 'public'}
base = {key(m) for m in methods(BASE)}

lines = []
missing = []
for m in rb:
    k = key(m)
    if m['final'] or k in base:
        continue
    if k not in gl:
        if m['abstract']:
            missing.append(k)
        continue
    params = ', '.join(f'{t} {n}' for t, n in m['params'])
    args = ', '.join(n for _, n in m['params'])
    call = f'gl.{m["name"]}({args})'
    ret = m['ret']
    if ret == 'void':
        body = (f'        if (shared) {{\n            lock.lock();\n            try {{\n                {call};\n            }} finally {{\n                lock.unlock();\n            }}\n            return;\n        }}\n'
                f'        {call};\n')
    else:
        body = (f'        if (shared) {{\n            lock.lock();\n            try {{\n                return {call};\n            }} finally {{\n                lock.unlock();\n            }}\n        }}\n'
                f'        return {call};\n')
    lines.append(f'    @Override {m["vis"]} {ret} {m["name"]}({params}) {{\n{body}    }}\n')

if missing:
    print('VulkanGL lacks abstract methods:', file=sys.stderr)
    for k in missing:
        print('  ' + k, file=sys.stderr)
    sys.exit(1)

header = '''package com.gtnewhorizons.angelica.vulkan;

import java.nio.ByteBuffer;
import java.nio.DoubleBuffer;
import java.nio.FloatBuffer;
import java.nio.IntBuffer;
import java.nio.ShortBuffer;

// Generated by vulkan/scripts/gen_backend.py from RenderBackend and VulkanGL; do not edit by hand.
public final class VulkanRenderBackend extends VulkanBackendBase {
'''
open(OUT, 'w').write(header + '\n'.join(lines) + '}\n')
print(f'wrote {len(lines)} forwarding methods to {OUT}')
